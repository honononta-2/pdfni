/// グリフ名→幅の表を二分探索で引く
fn width_from_table(table: &[(&str, f64)], glyph: &str) -> Option<f64> {
    table
        .binary_search_by_key(&glyph, |&(k, _)| k)
        .ok()
        .map(|i| table[i].1)
}

/// 標準14（正規化名）のグリフ幅。Courier 系は常に 600
pub fn standard14_glyph_width(font: &str, glyph: &str) -> Option<f64> {
    match font {
        "Courier" => Some(600.0),
        "Courier-Bold" => Some(600.0),
        "Courier-BoldOblique" => Some(600.0),
        "Courier-Oblique" => Some(600.0),
        "Helvetica" => width_from_table(HELVETICA_WIDTHS, glyph),
        "Helvetica-Bold" => width_from_table(HELVETICA_BOLD_WIDTHS, glyph),
        "Helvetica-BoldOblique" => width_from_table(HELVETICA_BOLDOBLIQUE_WIDTHS, glyph),
        "Helvetica-Oblique" => width_from_table(HELVETICA_OBLIQUE_WIDTHS, glyph),
        "Symbol" => width_from_table(SYMBOL_WIDTHS, glyph),
        "Times-Bold" => width_from_table(TIMES_BOLD_WIDTHS, glyph),
        "Times-BoldItalic" => width_from_table(TIMES_BOLDITALIC_WIDTHS, glyph),
        "Times-Italic" => width_from_table(TIMES_ITALIC_WIDTHS, glyph),
        "Times-Roman" => width_from_table(TIMES_ROMAN_WIDTHS, glyph),
        "ZapfDingbats" => width_from_table(ZAPFDINGBATS_WIDTHS, glyph),
        _ => None,
    }
}

/// メトリクス既定幅（等幅は 600、比例は 0）
pub fn standard14_default_width(font: &str) -> Option<f64> {
    match font {
        "Courier" => Some(600.0),
        "Courier-Bold" => Some(600.0),
        "Courier-BoldOblique" => Some(600.0),
        "Courier-Oblique" => Some(600.0),
        "Helvetica" => Some(0.0),
        "Helvetica-Bold" => Some(0.0),
        "Helvetica-BoldOblique" => Some(0.0),
        "Helvetica-Oblique" => Some(0.0),
        "Symbol" => Some(0.0),
        "Times-Bold" => Some(0.0),
        "Times-BoldItalic" => Some(0.0),
        "Times-Italic" => Some(0.0),
        "Times-Roman" => Some(0.0),
        "ZapfDingbats" => Some(0.0),
        _ => None,
    }
}

/// 正規化名が標準14メトリクスを持つか
pub fn has_standard14_metrics(font: &str) -> bool {
    standard14_default_width(font).is_some()
}

